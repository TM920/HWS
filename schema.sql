create table if not exists public.planner_data (
  user_id uuid primary key references auth.users(id) on delete cascade,
  payload jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

alter table public.planner_data enable row level security;
drop policy if exists "Users can read their own planner" on public.planner_data;
drop policy if exists "Users can create their own planner" on public.planner_data;
drop policy if exists "Users can update their own planner" on public.planner_data;
create policy "Users can read their own planner" on public.planner_data for select to authenticated using (auth.uid() = user_id);
create policy "Users can create their own planner" on public.planner_data for insert to authenticated with check (auth.uid() = user_id);
create policy "Users can update their own planner" on public.planner_data for update to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);

create table if not exists public.class_notes (
  id bigint generated by default as identity primary key,
  title text not null default 'Class note',
  body text not null,
  class_name text not null default '',
  user_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);
alter table public.class_notes enable row level security;
drop policy if exists "Signed-in users can read shared class notes" on public.class_notes;
drop policy if exists "Signed-in users can post class notes" on public.class_notes;
drop policy if exists "Authors can delete their notes" on public.class_notes;
create policy "Signed-in users can read shared class notes" on public.class_notes for select to authenticated using (true);
create policy "Signed-in users can post class notes" on public.class_notes for insert to authenticated with check (auth.uid() = user_id);
create policy "Authors can delete their notes" on public.class_notes for delete to authenticated using (auth.uid() = user_id);
